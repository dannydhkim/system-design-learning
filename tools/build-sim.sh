#!/usr/bin/env bash
# Rebuilds js/vendor/breakscale-sim.js from a checkout of https://github.com/workersio/breakscale (MIT).
#
#   tools/build-sim.sh                      # uses ~/Desktop/Development/breakscale
#   BREAKSCALE_DIR=/path/to/breakscale tools/build-sim.sh
#
# The game itself has no build step: this script only refreshes the one vendored file, and the result is committed.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
src="${BREAKSCALE_DIR:-$HOME/Desktop/Development/breakscale}"
out="$here/../js/vendor/breakscale-sim.js"
[ -d "$src/src/sim" ] || { echo "No Breakscale checkout at $src (git clone https://github.com/workersio/breakscale.git)"; exit 1; }
rev="$(git -C "$src" rev-parse --short HEAD)"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
# Resolve the @breakscale/sim alias without touching either repository.
mkdir -p "$tmp/node_modules/@breakscale" && ln -s "$src/src/sim" "$tmp/node_modules/@breakscale/sim"
cp "$here/sim-entry.ts" "$tmp/entry.ts"
(cd "$tmp" && bun build entry.ts --format=iife --minify --target=browser --outfile=bundle.js >/dev/null)
{
  echo "/*! Simulation engine from Breakscale (https://github.com/workersio/breakscale) at commit $rev."
  echo " *  Copyright (c) 2026 Breakscale contributors. MIT License: see js/vendor/breakscale-sim.LICENSE."
  echo " *  Generated by tools/build-sim.sh. Do not edit by hand. */"
  cat "$tmp/bundle.js"
} > "$out"
cp "$src/LICENSE" "$here/../js/vendor/breakscale-sim.LICENSE"
echo "Wrote $(basename "$out") from Breakscale $rev ($(wc -c < "$out") bytes)"
